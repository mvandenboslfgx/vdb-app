/**
 * Generate Database types from Mobile local Supabase (127.0.0.1:54522 only).
 * Fail-closed target guard runs before every generation.
 */
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const {
  MOBILE_LOCAL_DB_PORT,
  MOBILE_LOCAL_PROJECT_ID,
  LocalDbTargetError,
  assertMobileLocalDbTarget,
  assertPlausibleMobileTypesOutput,
  formatSafeTargetEvidence,
  parseDbUrlFromStatusEnv,
  readMobileSupabaseConfig,
  redactSecrets,
} = require('./lib/local-db-target-guard.cjs');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const DETERMINISTIC_HEADER = `/**
 * AUTO-GENERATED by scripts/gen-db-types.mjs — do not edit by hand.
 * Source: local Mobile Supabase schema (127.0.0.1:${MOBILE_LOCAL_DB_PORT}, project ${MOBILE_LOCAL_PROJECT_ID})
 */
`;

/**
 * Confirm config.toml + live `supabase status` both resolve to Mobile local :54522.
 * Generation then uses `--local` only after this guard passes (no password on argv).
 */
export function resolveValidatedLocalTarget(repoRoot = root) {
  const cfg = readMobileSupabaseConfig(repoRoot);

  let statusOut = '';
  try {
    statusOut = execSync('npx supabase status -o env', {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 2 * 1024 * 1024,
    });
  } catch (err) {
    const msg = redactSecrets(String(err?.stderr || err?.message || err));
    throw new LocalDbTargetError(
      `Mobile local Supabase is not reachable for type generation: ${msg}`,
      'STATUS_UNAVAILABLE',
    );
  }

  const parsed = parseDbUrlFromStatusEnv(statusOut);
  const safe = assertMobileLocalDbTarget({
    host: parsed.host,
    port: parsed.port,
    projectId: cfg.projectId,
  });

  if (cfg.port !== MOBILE_LOCAL_DB_PORT || parsed.port !== MOBILE_LOCAL_DB_PORT) {
    throw new LocalDbTargetError(
      `Live DB port mismatch (config=${cfg.port}, status=${parsed.port}, required=${MOBILE_LOCAL_DB_PORT})`,
      'PORT_MISMATCH',
    );
  }

  return {
    ...safe,
    evidence: formatSafeTargetEvidence(safe),
  };
}

/**
 * @param {{ outPath?: string, repoRoot?: string, quiet?: boolean }} [opts]
 */
export function generateMobileDbTypes(opts = {}) {
  const repoRoot = opts.repoRoot ?? root;
  const outPath = opts.outPath ?? resolve(repoRoot, 'src/types/database.generated.ts');
  const target = resolveValidatedLocalTarget(repoRoot);

  if (!opts.quiet) {
    console.log(
      `Generating types from Mobile local DB (hostclass=${target.evidence.hostclass}, port=${target.evidence.port}, project=${target.evidence.localProjectId})…`,
    );
  }

  let raw;
  try {
    raw = execSync('npx supabase gen types typescript --local', {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 20 * 1024 * 1024,
    });
  } catch (err) {
    const errText = redactSecrets(String(err?.stderr || err?.message || err));
    throw new LocalDbTargetError(`Type generation failed: ${errText}`, 'GENERATION_FAILED');
  }

  const typesBody =
    String(raw || '')
      .replace(/\r\n/g, '\n')
      .trim() + '\n';
  assertPlausibleMobileTypesOutput(typesBody);

  mkdirSync(dirname(outPath), { recursive: true });
  const full = DETERMINISTIC_HEADER + typesBody;
  writeFileSync(outPath, full, 'utf8');

  if (!opts.quiet) {
    console.log(`Wrote ${outPath} (${Buffer.byteLength(full, 'utf8')} bytes)`);
  }

  return {
    outPath,
    bytes: Buffer.byteLength(full, 'utf8'),
    evidence: target.evidence,
    typesBody,
    full,
  };
}

export function stripGeneratedHeader(text) {
  return String(text)
    .replace(/^\/\*\*[\s\S]*?\*\//, '')
    .replace(/\r\n/g, '\n')
    .trim();
}

export function readCanonicalTypesBody(repoRoot = root) {
  const outPath = resolve(repoRoot, 'src/types/database.generated.ts');
  if (!existsSync(outPath)) {
    throw new LocalDbTargetError('Missing src/types/database.generated.ts', 'MISSING_TYPES_FILE');
  }
  const raw = readFileSync(outPath, 'utf8');
  assertPlausibleMobileTypesOutput(raw, { path: outPath });
  return stripGeneratedHeader(raw);
}

const isMain =
  process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
  try {
    const outIdx = process.argv.indexOf('--out');
    const outPath = outIdx >= 0 ? process.argv[outIdx + 1] : undefined;
    generateMobileDbTypes({ outPath });
  } catch (err) {
    console.error(redactSecrets(err?.message || String(err)));
    process.exit(1);
  }
}
